#!/usr/bin/env node
import { spawnSync } from "node:child_process";
import {
  accessSync,
  chmodSync,
  constants as fsConstants,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";

import {
  collectBlockers,
  isSeverityBand,
  LEVEL_RANK,
  readAllowlist,
  readScannerOutput,
  validateAllowlist,
} from "./sca-gate-core.ts";
import type { AllowEntry } from "./sca-gate-core.ts";

const OSV_ARCHES = {
  arm64: "arm64",
  x64: "amd64",
} satisfies Partial<Record<typeof process.arch, string>>;

const isOsvArch = (arch: string): arch is keyof typeof OSV_ARCHES =>
  Object.hasOwn(OSV_ARCHES, arch);

const root = path.resolve(import.meta.dirname, "../..");

const allowlistPath = path.resolve(
  root,
  process.env.SCA_ALLOWLIST_PATH ?? ".github/security/sca-allowlist.json"
);

const auditLevel = (process.env.SCA_AUDIT_LEVEL ?? "high").toLowerCase();
const today = new Date().toISOString().slice(0, 10);
const lockfile = "bun.lock";

if (!isSeverityBand(auditLevel)) {
  console.error(
    `::error::invalid SCA_AUDIT_LEVEL=${auditLevel} (use low|moderate|high|critical)`
  );
  process.exit(2);
}

const minRank = LEVEL_RANK[auditLevel];

const readAllowlistText = (): string => {
  try {
    return readFileSync(allowlistPath, "utf-8");
  } catch (error) {
    console.error(
      `::error::sca-allowlist: cannot read ${allowlistPath}: ${String(error)}`
    );

    return process.exit(1);
  }
};

const allowlist = readAllowlist(readAllowlistText());

if (!allowlist.ok) {
  console.error(`::error::sca-allowlist: ${allowlist.error}`);
  process.exit(1);
}

const { active, errors } = validateAllowlist(allowlist.value, today);

if (errors.length > 0) {
  for (const line of errors) {
    console.error(`::error::sca-allowlist: ${line}`);
  }

  process.exit(1);
}

const isExecutable = (candidate: string): boolean => {
  try {
    accessSync(candidate, fsConstants.X_OK);

    return true;
  } catch {
    return false;
  }
};

const which = (cmd: string): string | null => {
  for (const dir of (process.env.PATH ?? "").split(path.delimiter)) {
    if (!dir) {
      continue;
    }

    const candidate = path.join(dir, cmd);

    if (isExecutable(candidate)) {
      return candidate;
    }
  }

  return null;
};

const ensureOsvScanner = (): string => {
  const fromEnv = process.env.OSV_SCANNER_BIN;

  if (fromEnv !== undefined && fromEnv !== "") {
    return fromEnv;
  }

  const onPath = which("osv-scanner");

  if (onPath !== null && onPath !== "") {
    return onPath;
  }

  const version = process.env.OSV_SCANNER_VERSION ?? "2.4.0";

  const platform =
    process.platform === "darwin" || process.platform === "linux"
      ? process.platform
      : undefined;

  const arch = isOsvArch(process.arch) ? OSV_ARCHES[process.arch] : undefined;

  if (platform === undefined || arch === undefined) {
    throw new Error(
      `osv-scanner not found and no binary for ${process.platform}/${process.arch}`
    );
  }

  const cacheDir = path.resolve(root, "node_modules/.cache/osv-scanner");
  mkdirSync(cacheDir, { recursive: true });

  const dest = path.resolve(
    cacheDir,
    `osv-scanner-${version}-${platform}-${arch}`
  );

  if (existsSync(dest)) {
    return dest;
  }

  const url = `https://github.com/google/osv-scanner/releases/download/v${version}/osv-scanner_${platform}_${arch}`;
  console.error(`Downloading osv-scanner v${version}…`);

  const curl = spawnSync("curl", ["-sSfL", url, "-o", dest], {
    stdio: "inherit",
  });

  if (curl.status !== 0) {
    throw new Error(
      `failed to download osv-scanner (curl exit ${curl.status}): ${url}`
    );
  }

  chmodSync(dest, 0o755);

  return dest;
};

const writeConfig = (activeEntries: readonly AllowEntry[]) => {
  const lines = [
    "# Generated by scripts/security/sca-gate.ts — do not edit by hand.",
    `# Source: ${allowlistPath}`,
    "",
  ];

  for (const e of activeEntries) {
    lines.push(
      "[[IgnoredVulns]]",
      `id = ${JSON.stringify(e.id)}`,
      `ignoreUntil = ${e.expires}`
    );

    if (e.reason !== undefined && e.reason !== "") {
      lines.push(`reason = ${JSON.stringify(e.reason)}`);
    }

    lines.push("");
  }

  const configDir = mkdtempSync(path.join(tmpdir(), "osv-scanner-config-"));
  const configPath = path.join(configDir, "allowlist.toml");

  writeFileSync(configPath, lines.join("\n"), { flag: "wx", mode: 0o600 });

  return { configDir, configPath };
};

const bin = ensureOsvScanner();
const { configDir, configPath } = writeConfig(active);

console.log(
  `Running osv-scanner on bun.lock (${active.length} active allowlist entries, gate ≥ ${auditLevel})`
);

const proc = (() => {
  try {
    return spawnSync(
      bin,
      [
        "scan",
        "source",
        "-L",
        lockfile,
        "--format=json",
        `--config=${configPath}`,
      ],
      {
        cwd: root,
        encoding: "utf-8",
        maxBuffer: 64 * 1024 * 1024,
        stdio: ["ignore", "pipe", "inherit"],
      }
    );
  } finally {
    rmSync(configDir, { force: true, recursive: true });
  }
})();

const stdout = proc.stdout ?? "";
const code = proc.status ?? 1;

if (code !== 0 && code !== 1) {
  console.error(`::error::osv-scanner exited with unexpected code ${code}`);
  process.exit(code);
}

const scan = readScannerOutput(stdout, code);

if (!scan.ok) {
  console.error(`::error::failed to read osv-scanner output: ${scan.error}`);
  console.error(stdout.slice(0, 2000));
  process.exit(1);
}

const blockers = collectBlockers(scan.value, minRank);

if (blockers.length === 0) {
  console.log(`SCA gate passed (no findings ≥ ${auditLevel}).`);
  process.exit(0);
}

console.error(
  `::error::SCA gate failed: ${blockers.length} finding(s) ≥ ${auditLevel}`
);

for (const b of blockers) {
  console.error(
    `- ${b.severity.toUpperCase()} ${b.id} ${b.package}@${b.version}: ${b.summary}`
  );
}

process.exit(1);
